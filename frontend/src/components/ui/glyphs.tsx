/** A solid brand mark on lucide's 24 grid, coloured by `currentColor`. */
function solidGlyph(paths: string[]) {
  return function Glyph({ size = 20, strokeWidth: _sw, absoluteStrokeWidth: _asw, ...props }: LucideProps) {
    return (
      <svg viewBox="0 0 24 24" width={size} height={size} fill="currentColor" aria-hidden {...props}>
        {paths.map((d) => (
          <path key={d} d={d} />
        ))}
      </svg>
    );
  };
}

